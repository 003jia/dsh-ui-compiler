import { readFileSync } from 'node:fs'
import { designStates, type DesignNode, type DesignPage, type DesignState, type DesignWarning } from '../../ir/index.ts'

type Literal = string | number | boolean
type MappingProp =
  | { as: 'callback' }
  | { from: string; as: 'copy' }
  | { from: string; as?: never; type?: 'string' | 'number' | 'boolean'; values?: Literal[]; default?: Literal }
type CornerRadiusMapping = { pixels: number; token: string }
type ComponentMapping =
  | { ignore: true }
  | {
      import: { from: '@deepseek-ai/dsh-client-ui-primitives'; name: string }
      props: Record<string, MappingProp>
      cornerRadius?: CornerRadiusMapping
    }

export type CompilerMap = {
  $schema?: string
  target: { framework: 'react18'; styles: 'css-modules'; copy: 'zh-en-dictionary' }
  packages: { primitives: string; theme: string }
  components: Record<string, ComponentMapping>
}

type Inventory = { components: Record<string, { props: Record<string, { required: boolean }> }> }
type TokenType = 'color' | 'dimension' | 'fontFamily'
type Tokens = { light: Record<string, { $type: TokenType; $value?: string | { value?: number; unit?: string } }>; $extensions?: { 'dev.uic'?: { cssOnly?: { light?: Record<string, unknown> } } } }
type Direction = 'vertical' | 'horizontal'
type DataShape = { fields: Set<string>; lists: Map<string, DataShape>; objects: Map<string, DataShape> }
type Scope = { shape: DataShape; expression: string; depth: number; direction?: Direction }
const generated = 'Generated by uic. Edit the design or mapping instead.'
const indent = (depth: number) => '  '.repeat(depth)
const quote = (value: Literal) => JSON.stringify(value)
const own = <T>(record: Record<string, T>, key: string) => Object.hasOwn(record, key) ? record[key] : undefined
const emptyShape = (): DataShape => ({ fields: new Set(), lists: new Map(), objects: new Map() })
const decimal = /^-?(?:\d+\.?\d*|\.\d+)$/
const validProp = /^[A-Za-z][A-Za-z0-9-]*$/
const previewIconPaths = readCatalog<Record<string, string>>('preview-icons.json')

function readCatalog<T>(filename: string): T {
  return JSON.parse(readFileSync(new URL(`../../../tokens/${filename}`, import.meta.url), 'utf8')) as T
}

function identifierPart(value: string) {
  return (value.match(/[A-Za-z0-9]+/g) ?? [])
    .map(word => word[0].toUpperCase() + word.slice(1)).join('')
}

function instanceName(name: string) {
  return name.split(/[·[]/, 1)[0].trim()
}

function slug(name: string) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase()
}

function designComment(node: DesignNode) {
  const text = `${node.id} · ${node.name}`.replace(/\*\//g, '* /').replace(/[\r\n\u2028\u2029]/g, ' ')
  return `{/* ${text} */}`
}

function nodeChildren(node: DesignNode) {
  return node.kind === 'stack' ? node.children : []
}

function colorOf(value: unknown): unknown {
  if (typeof value === 'string') return value
  if (!Array.isArray(value)) return undefined
  const visible = value.filter(paint => paint && typeof paint === 'object' && paint.enabled !== false)
  return visible.length === 1 && visible[0].type === 'solid' ? visible[0].color : undefined
}

function cssLength(value: unknown) {
  if (typeof value === 'number' && Number.isFinite(value)) return `${value}px`
  if (typeof value === 'string' && decimal.test(value)) return `${Number(value)}px`
}

function layoutAlign(value: unknown) {
  switch (value) {
    case 'start': return 'flex-start'
    case 'end': return 'flex-end'
    case 'center': return 'center'
    case 'stretch': return 'stretch'
    case 'space_between': return 'space-between'
    case 'space_around': return 'space-around'
    case 'space_evenly': return 'space-evenly'
  }
}

export function emitDshReact(page: DesignPage, mapping: CompilerMap, name: string, options: { nativePreviewLayout?: boolean } = {}) {
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Invalid generated component name: ${name}`)
  const view = name.endsWith('View') ? name : `${name}View`
  const locales = `${slug(view.slice(0, -4) || view)}.locales.generated`
  const styleFile = `${view}.generated.module.css`
  const inventory = readCatalog<Inventory>('primitives.inventory.json')
  const tokens = readCatalog<Tokens>('dsw.tokens.json')
  const previewRadii = new Map<number, string>()
  if (options.nativePreviewLayout) {
    for (const [key, token] of Object.entries(tokens.light)) {
      if (!key.startsWith('--dsw-radius-') || token.$type !== 'dimension') continue
      const size = token.$value
      if (typeof size === 'object' && size.unit === 'px' && typeof size.value === 'number') {
        previewRadii.set(size.value, `var(${key})`)
      }
    }
  }
  const cssOnlyTokens = tokens.$extensions?.['dev.uic']?.cssOnly?.light ?? {}
  const warnings: DesignWarning[] = [...page.warnings]
  const incompleteIds = new Set(page.warnings.map(warning => warning.id))
  const styles: string[] = []
  const copy = new Map<string, string>()
  const imports = new Set<string>()
  const callbacks = new Map<string, string>()
  const data = emptyShape()
  const visibleIds = new Set<string>()
  let needsNoop = false

  function warn(node: DesignNode, message: string, affectsCoverage = true) {
    warnings.push({ id: node.id, name: node.name, message })
    if (affectsCoverage) incompleteIds.add(node.id)
  }

  function registerCopy(node: DesignNode, key: string, value: string) {
    let chosen = key || node.id
    const base = chosen
    for (let suffix = 1; copy.has(chosen) && copy.get(chosen) !== value; suffix++) {
      chosen = `${base}.${node.id}${suffix === 1 ? '' : `.${suffix}`}`
    }
    if (!copy.has(chosen)) {
      copy.set(chosen, value)
      warn(node, `翻译待补 ${chosen}`, false)
    }
    return `labels[${quote(chosen)}]`
  }

  function binding(node: DesignNode, field: string, scope: Scope) {
    const parts = field.split('.')
    const head = parts[0]
    const reserved = scope.depth === 0
      ? ['state', 'labels'].includes(head) || callbacks.has(head)
      : head === 'id' && parts.length > 1
    let shape = scope.shape
    for (const [index, part] of parts.entries()) {
      const leaf = index === parts.length - 1
      if (reserved || shape.lists.has(part) || (leaf ? shape.objects.has(part) : shape.fields.has(part))) {
        warn(node, `动态字段名 ${field} 与列表、对象或内置 prop 冲突`)
        return 'null'
      }
      if (leaf) {
        shape.fields.add(part)
      } else {
        const child = shape.objects.get(part) ?? emptyShape()
        shape.objects.set(part, child)
        shape = child
      }
    }
    return `${scope.expression}[${quote(head)}]${parts.slice(1).map(part => `?.[${quote(part)}]`).join('')}`
  }

  function cssToken(value: unknown, expected: TokenType) {
    if (typeof value !== 'string') return
    const property = value.startsWith('--dsw-')
      ? value : value.startsWith('$dsw.') ? `--${value.slice(1).replace(/\./g, '-')}` : ''
    const type = own(tokens.light, property)?.$type
    const cssFontStack = expected === 'fontFamily' && Object.hasOwn(cssOnlyTokens, property) &&
      (property === '--dsw-font-family' || property === '--dsw-font-family-brand')
    if (type === expected || cssFontStack) return `var(${property})`
  }

  function nodeClass(node: DesignNode, direction?: Direction, radiusMapping?: CornerRadiusMapping) {
    const declarations = new Map<string, string>()
    const set = (property: string, value: string | undefined) => {
      if (value !== undefined) declarations.set(property, value)
    }
    // The managed canvas stores unbound layout dimensions as numbers. The saved
    // preview can paint those faithfully while the export still reports missing bindings.
    const nativeLength = (property: string, value: unknown) => {
      if (!options.nativePreviewLayout || typeof value !== 'number' || !Number.isFinite(value) || value < 0) return
      if (property === 'border-radius') return previewRadii.get(value) ?? cssLength(value)
      if (property === 'padding' || property === 'gap') return cssLength(value)
    }
    const setToken = (property: string, value: unknown, numericZero = false) => {
      if (value === undefined || value === null || (numericZero && (value === 0 || value === '0'))) return
      const token = cssToken(value, property.includes('color') ? 'color' : 'dimension')
      if (token) set(property, token)
      else {
        warn(node, `${property} 未绑定有效的 DSH token（${JSON.stringify(value)}）`)
        set(property, nativeLength(property, value))
      }
    }

    const sizing = node.kind === 'stack' ? { ...node.style, ...node.layout } : node.style
    for (const [property, field] of Object.entries({
      width: 'width', height: 'height',
      'min-width': 'minWidth', 'max-width': 'maxWidth', 'min-height': 'minHeight', 'max-height': 'maxHeight',
    })) {
      const value = sizing[field]
      if (value === 'fill_container') {
        if ((property === 'width' && direction === 'horizontal') || (property === 'height' && direction === 'vertical')) {
          set('flex', '1 1 0')
          set(`min-${property}`, '0')
        } else set(property, '100%')
      } else if (value === 'fit_content') {
        set(property, 'fit-content')
      } else if (value !== undefined) {
        const length = cssLength(value) ?? cssToken(value, 'dimension')
        if (length) set(property, length)
        else warn(node, `${property} 尺寸规则未映射`)
      }
    }
    if (node.kind === 'stack') {
      const { layout, gap, padding, alignItems, justifyContent, clipContent } = node.layout
      if (layout === 'horizontal' || layout === 'vertical') {
        set('display', 'flex')
        set('flex-direction', layout === 'horizontal' ? 'row' : 'column')
        set('align-items', layoutAlign(alignItems))
        set('justify-content', layoutAlign(justifyContent))
      } else if (node.children.length > 0) {
        warn(node, '非自动布局容器需补全定位')
      }
      setToken('gap', gap, true)
      if (Array.isArray(padding)) {
        if ([1, 2, 4].includes(padding.length)) {
          const values = padding.map(value => value === 0 || value === '0' ? '0' : cssToken(value, 'dimension'))
          if (values.every(Boolean)) set('padding', values.join(' '))
          else {
            warn(node, `padding 未绑定有效的 DSH token（${JSON.stringify(padding)}）`)
            const preview = values.map((value, i) => value ?? nativeLength('padding', padding[i]))
            if (preview.every(Boolean)) set('padding', preview.join(' '))
          }
        } else warn(node, 'padding 结构未映射')
      } else setToken('padding', padding, true)
      if (clipContent === true) set('overflow', 'hidden')
    }
    const { fill, stroke, cornerRadius, opacity, rotation, effect, blendMode } = node.style
    if (typeof opacity === 'number' && opacity >= 0 && opacity <= 1 && opacity !== 1) set('opacity', String(opacity))
    if (typeof rotation === 'number' && Number.isFinite(rotation) && rotation !== 0) set('transform', `rotate(${rotation}deg)`)
    if (effect && (!Array.isArray(effect) || effect.length > 0)) warn(node, '图层效果未映射')
    if (blendMode && blendMode !== 'normal') warn(node, '图层混合模式未映射')
    if (fill !== undefined && (!Array.isArray(fill) || fill.length > 0)) {
      const color = colorOf(fill)
      if (color !== undefined) setToken(node.kind === 'text' ? 'color' : 'background-color', color)
      else warn(node, '填充类型未映射')
    }
    if (stroke && typeof stroke === 'object' && !Array.isArray(stroke)) {
      const border = stroke as { thickness?: unknown; fill?: unknown }
      if (border.thickness !== 0) {
        const width = cssLength(border.thickness)
        const color = colorOf(border.fill)
        const token = cssToken(color, 'color')
        if (width && token) set('border', `${width} solid ${token}`)
        else warn(node, '描边宽度未映射或颜色未绑定有效的 DSH token')
      }
    }
    if (Array.isArray(cornerRadius) && cornerRadius.length === 4) {
      const radius = cornerRadius.map(value => value === 0 || value === '0' ? '0' : cssToken(value, 'dimension'))
      if (radius.every(Boolean)) set('border-radius', radius.join(' '))
      else {
        warn(node, `border-radius 未绑定有效的 DSH token（${JSON.stringify(cornerRadius)}）`)
        const preview = radius.map((value, i) => value ?? nativeLength('border-radius', cornerRadius[i]))
        if (preview.every(Boolean)) set('border-radius', preview.join(' '))
      }
    } else {
      const radius = radiusMapping && cornerRadius === radiusMapping.pixels
        ? radiusMapping.token
        : cornerRadius
      setToken('border-radius', radius, true)
    }
    if (node.kind === 'text') {
      const { fontSize, fontWeight, fontStyle, lineHeight, fontFamily, letterSpacing,
        textAlign, underline, strikethrough } = node.style
      set('font-size', cssLength(fontSize) ?? cssToken(fontSize, 'dimension'))
      set('letter-spacing', cssLength(letterSpacing) ?? cssToken(letterSpacing, 'dimension'))
      if (typeof fontWeight === 'number' && Number.isFinite(fontWeight) ||
        typeof fontWeight === 'string' && /^\d+$/.test(fontWeight)) set('font-weight', String(fontWeight))
      if (typeof lineHeight === 'number' && Number.isFinite(lineHeight)) set('line-height', String(lineHeight))
      if (fontStyle === 'italic' || fontStyle === 'oblique') set('font-style', fontStyle)
      if (underline === true || strikethrough === true) {
        set('text-decoration-line', [underline === true ? 'underline' : '', strikethrough === true ? 'line-through' : '']
          .filter(Boolean).join(' '))
      }
      if (typeof fontFamily === 'string') {
        const token = cssToken(fontFamily, 'fontFamily')
        if (token) set('font-family', token)
        else if (/^[\p{L}\d ,'"-]+$/u.test(fontFamily)) set('font-family', fontFamily)
      }
      if (textAlign === 'left' || textAlign === 'center' || textAlign === 'right' || textAlign === 'justify') {
        set('text-align', textAlign)
      }
      if (node.text.includes('\n')) set('white-space', 'pre-wrap')
    }
    if (declarations.size === 0) return ''
    if (declarations.has('border') || declarations.has('padding')) set('box-sizing', 'border-box')
    const className = `node${styles.length + 1}`
    styles.push(`.${className} {\n${[...declarations].map(([property, value]) =>
      `  ${property}: ${value};`).join('\n')}\n}`)
    return ` className={styles.${className}}`
  }

  function callback(node: DesignNode, scope: Scope, component: string, prop: string, count: number, required: boolean) {
    const event = prop.replace(/^on/, '')
    const label = identifierPart(instanceName(node.name)) || identifierPart(component)
    const base = `on${label}${count > 1 ? event : ''}`
    const input = `NonNullable<ComponentProps<typeof ${component}>[${quote(prop)}]>`
    const type = scope.depth > 0 ? `(itemId: string | number, ...args: Parameters<${input}>) => void` : input
    let key = base
    for (let suffix = 1; data.fields.has(key) || data.lists.has(key) || data.objects.has(key) ||
      (callbacks.has(key) && callbacks.get(key) !== type); suffix++) {
      key = `${base}${event}${suffix === 1 ? '' : suffix}`
    }
    callbacks.set(key, type)
    if (scope.depth > 0) return `(...args) => props.${key}?.(${scope.expression}.id, ...args)`
    if (required) needsNoop = true
    return `props.${key}${required ? ' ?? noop' : ''}`
  }

  function emitInstance(node: Extract<DesignNode, { kind: 'instance' }>, scope: Scope, depth: number) {
    const entry = own(mapping.components, node.component)
    if (!entry) return placeholder(node, depth, `组件未映射 ${node.component}`, scope.direction)
    if ('ignore' in entry) {
      warn(node, `映射表显式忽略 ${node.component}`)
      return ''
    }
    const component = entry.import.name
    const props = own(inventory.components, component)?.props
    if (!props || !/^[A-Z][A-Za-z0-9]*$/.test(component)) {
      return placeholder(node, depth, `组件类型不可用 ${component}`, scope.direction)
    }
    const attributes = new Map<string, string>()
    const pendingCallbacks: string[] = []
    const pendingCopy = new Map<string, { field: string; text: string }>()
    for (const [prop, definition] of Object.entries(entry.props)) {
      if (!validProp.test(prop) || !own(props, prop)) {
        warn(node, `组件属性未映射 ${component}.${prop}`)
        continue
      }
      if (definition.as === 'callback') {
        pendingCallbacks.push(prop)
        continue
      }
      const field = definition.from.split('.')[1]
      if (definition.as === 'copy') {
        const text = own(node.text, field)
        if (text === undefined) {
          warn(node, `组件缺少文案 ${definition.from}`)
          continue
        }
        pendingCopy.set(prop, { field, text })
        continue
      }
      let value = own(node.variants, field)
      const accepts = (literal: Literal) =>
        (!definition.type || typeof literal === definition.type) &&
        (!definition.values || definition.values.includes(literal)) &&
        (typeof literal !== 'number' || Number.isFinite(literal))
      if (value !== undefined && !accepts(value)) {
        warn(node, `组件变体值无效 ${definition.from}`)
        value = undefined
      }
      if (value === undefined) value = definition.default
      if (value !== undefined && accepts(value)) attributes.set(prop, quote(value))
    }
    const missing = Object.entries(props).filter(([prop, metadata]) =>
      metadata.required && prop !== 'className' && prop !== 'key' &&
      !attributes.has(prop) && !pendingCallbacks.includes(prop) && !pendingCopy.has(prop)).map(([prop]) => prop)
    if (missing.length > 0) return placeholder(node, depth, `组件缺少必需属性 ${component}.${missing.join(', ')}`, scope.direction)

    for (const [prop, { field, text }] of pendingCopy) {
      attributes.set(prop, registerCopy(node, `${instanceName(node.name)}.${field}`, text))
    }
    for (const prop of pendingCallbacks) {
      attributes.set(prop, callback(node, scope, component, prop, pendingCallbacks.length, props[prop].required))
    }
    const css = own(props, 'className') && !attributes.has('className')
      ? nodeClass(node, scope.direction, entry.cornerRadius)
      : ''
    imports.add(component)
    return `${indent(depth)}${designComment(node)}\n${indent(depth)}<${component}${css}${[...attributes].map(([prop, value]) =>
      ` ${prop}={${value}}`).join('')} />`
  }

  function placeholder(node: DesignNode, depth: number, reason: string, direction?: Direction) {
    warn(node, reason)
    if (options.nativePreviewLayout) return ''
    return `${indent(depth)}${designComment(node)}\n${indent(depth)}<div data-uic-unmapped={${quote(node.id)}}${nodeClass(node, direction)} />`
  }

  function skipSample(node: DesignNode) {
    if (node.name.startsWith('_')) return
    visibleIds.add(node.id)
    warn(node, '重复列表示例仅保留第一项')
    for (const child of nodeChildren(node)) skipSample(child)
  }

  function emitNode(node: DesignNode, scope: Scope, depth: number): string {
    if (node.name.startsWith('_')) return ''
    visibleIds.add(node.id)
    if (node.kind === 'instance') return emitInstance(node, scope, depth)
    if (node.kind === 'asset') {
      if (options.nativePreviewLayout && node.asset === 'icon' && Object.hasOwn(previewIconPaths, node.ref)) {
        const color = cssToken(colorOf(node.style.fill), 'color') ?? 'var(--dsw-alias-label-secondary)'
        const style = { width: cssLength(node.style.width), height: cssLength(node.style.height), flexShrink: 0, color }
        return `${indent(depth)}<svg aria-hidden="true" style={${JSON.stringify(style)}} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.75} strokeLinecap="round" strokeLinejoin="round"><path d=${quote(previewIconPaths[node.ref])} /></svg>`
      }
      return placeholder(node, depth, `资源未映射 ${node.ref}`, scope.direction)
    }
    if (node.kind === 'unmapped') return placeholder(node, depth, node.reason, scope.direction)

    const attribution = `${indent(depth)}${designComment(node)}\n${indent(depth)}`
    const attributes = ` data-uic-node={${quote(node.id)}}${nodeClass(node, scope.direction)}`
    if (node.kind === 'text') {
      const content = node.binding ? binding(node, node.binding, scope) : registerCopy(node, node.name, node.text)
      return `${attribution}<span${attributes}>{${content}}</span>`
    }
    const direction = node.layout.layout === 'horizontal' || node.layout.layout === 'vertical'
      ? node.layout.layout : undefined
    const children = node.children.filter(child => !child.name.startsWith('_'))
    if (!node.repeat) {
      const lines = children.map(child => emitNode(child, { ...scope, direction }, depth + 1)).filter(Boolean)
      return lines.length
        ? `${attribution}<div${attributes}>\n${lines.join('\n')}\n${indent(depth)}</div>`
        : `${attribution}<div${attributes} />`
    }
    const [template, ...samples] = children
    if (!template || scope.shape.fields.has(node.repeat) || scope.shape.objects.has(node.repeat) ||
      (scope.depth > 0 && node.repeat === 'id') ||
      (scope.depth === 0 && (['state', 'labels'].includes(node.repeat) || callbacks.has(node.repeat)))) {
      for (const child of children) skipSample(child)
      warn(node, `重复列表 ${node.repeat} 缺少模板或与 prop 冲突`)
      return `${attribution}<div${attributes} />`
    }
    const shape = scope.shape.lists.get(node.repeat) ?? emptyShape()
    scope.shape.lists.set(node.repeat, shape)
    const item = scope.depth === 0 ? 'item' : `item${scope.depth + 1}`
    const itemScope: Scope = { shape, expression: item, depth: scope.depth + 1, direction }
    // A design preview shows the actual numbered exemplars. Keep their source index
    // on the fixture so filtering or reordering cannot change which controls it shows.
    const numbered = options.nativePreviewLayout ? children.flatMap(child => {
      const match = /^([A-Za-z_$][\w$]*)\[(\d+)\]$/u.exec(child.name)
      return match && match[1] === node.repeat ? [{ child, index: Number(match[2]) }] : []
    }) : []
    let contents: string
    if (numbered.length > 1 && numbered[0].child === template) {
      shape.fields.add('previewRowIndex')
      contents = numbered.map(({ child, index }) => [
        `${indent(depth + 3)}{(${item}.previewRowIndex ?? 0) === ${index} && <>`,
        emitNode(child, itemScope, depth + 4),
        `${indent(depth + 3)}</>}`,
      ].join('\n')).join('\n')
    } else {
      for (const sample of samples) skipSample(sample)
      contents = emitNode(template, itemScope, depth + 3)
    }
    return [
      `${attribution}<div${attributes}>`,
      `${indent(depth + 1)}{(${scope.expression}[${quote(node.repeat)}] ?? []).map((${item}) => (`,
      `${indent(depth + 2)}<Fragment key={${item}.id}>`,
      contents,
      `${indent(depth + 2)}</Fragment>`,
      `${indent(depth + 1)}))}`,
      `${indent(depth)}</div>`,
    ].filter(Boolean).join('\n')
  }

  function dataProps(shape: DataShape, depth: number, itemRoot = false): string[] {
    const lines = [...shape.fields].sort().filter(field => !(itemRoot && field === 'id'))
      .map(field => `${indent(depth)}readonly ${quote(field)}?: string | number`)
    for (const [field, object] of [...shape.objects].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
      lines.push(`${indent(depth)}readonly ${quote(field)}?: {`,
        ...dataProps(object, depth + 1), `${indent(depth)}}`)
    }
    for (const [field, item] of [...shape.lists].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
      lines.push(`${indent(depth)}readonly ${quote(field)}?: ReadonlyArray<{`,
        `${indent(depth + 1)}readonly id: string | number`,
        ...dataProps(item, depth + 1, true), `${indent(depth)}}>`)
    }
    return lines
  }

  const byState = new Map<DesignState, string>()
  for (const state of designStates) {
    const frame = page.frames.find(candidate => candidate.state === state)
    if (frame) byState.set(state, emitNode(frame.node, { shape: data, expression: 'props', depth: 0 }, 5))
  }
  const stateCode = [...byState].filter(([state]) => state !== 'default').flatMap(([state, jsx]) => [
    `    case ${quote(state)}:`,
    ...(jsx ? ['      return (', '        <>', jsx, '        </>', '      )'] : ['      return null']),
  ])
  const defaultJsx = byState.get('default')
  stateCode.push('    default:',
    ...(defaultJsx ? ['      return (', '        <>', defaultJsx, '        </>', '      )'] : ['      return null']))

  const lines = [
    `// ${generated}`,
    ...(data.lists.size ? [`import { Fragment } from 'react'`] : []),
    ...(callbacks.size ? [`import type { ComponentProps } from 'react'`] : []),
    ...(imports.size ? [`import { ${[...imports].sort().join(', ')} } from '@deepseek-ai/dsh-client-ui-primitives'`] : []),
    ...(styles.length ? [`import styles from './${styleFile}'`] : []),
    ...(copy.size ? [`import { zh } from './${locales}'`] : []),
    '',
    ...(needsNoop ? ['function noop() {}', ''] : []),
    `export interface ${view}Props {`,
    `  readonly state?: ${designStates.map(quote).join(' | ')}`,
    ...(copy.size ? ['  readonly labels?: { readonly [Key in keyof typeof zh]: string }'] : []),
    ...dataProps(data, 1),
    ...[...callbacks].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
      .map(([key, type]) => `  readonly ${key}?: ${type}`),
    '}',
    '',
    `export function ${view}(props: ${view}Props) {`,
    ...(copy.size ? ['  const labels = props.labels ?? zh'] : []),
    `  switch (props.state ?? 'default') {`,
    ...stateCode,
    '  }',
    '}',
    '',
  ]
  const entries = [...copy].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
  const exportLocale = (language: 'zh' | 'en') => [
    `export const ${language} = {`,
    ...entries.map(([key, value]) => `  [${quote(key)}]: ${quote(language === 'en' ? `TODO: ${value}` : value)},`),
    language === 'zh' ? '} satisfies Record<string, string>' : '} satisfies Record<keyof typeof zh, string>',
  ].join('\n')
  const total = visibleIds.size
  const covered = [...visibleIds].filter(id => !incompleteIds.has(id)).length
  return {
    files: {
      [`${view}.generated.tsx`]: lines.join('\n'),
      [styleFile]: `/* ${generated} */\n${styles.length ? `\n${styles.join('\n\n')}\n` : ''}`,
      [`${locales}.ts`]: `// ${generated}\n\n${exportLocale('zh')}\n\n${exportLocale('en')}\n`,
    },
    report: { total, covered, warnings },
  }
}
